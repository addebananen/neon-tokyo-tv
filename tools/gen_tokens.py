#!/usr/bin/env python3
"""Turns design/neon-tokens.json into the Swift and Kotlin token files.

    python3 tools/gen_tokens.py          # write the files
    python3 tools/gen_tokens.py --check  # fail if a generated file is out of date (CI)
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TOKENS = json.loads((ROOT / "design/neon-tokens.json").read_text())
SWIFT = ROOT / "apple/NeonTokyo/Shared/Theme/NeonTokens.swift"
KOTLIN = ROOT / "desktop/src/main/kotlin/com/neontokyo/desktop/theme/NeonTokens.kt"
COLOR_KEYS = ["primary", "secondary", "warm", "background", "surface", "panel", "text", "muted", "error"]
HEADER = "Generated by tools/gen_tokens.py from design/neon-tokens.json. Do not edit; change the JSON."


def camel(s):
    parts = s.split("_")
    return parts[0] + "".join(p.title() for p in parts[1:])


def hex6(s):
    return s.lstrip("#").upper()


def swift():
    out = [f"// {HEADER}", "", "import SwiftUI", "", "enum NeonTokens {"]
    for t in TOKENS["themes"]:
        out.append(f"    static let {camel(t['id'])} = NeonThemeTokens(")
        out.append(f"        id: \"{t['id']}\", name: \"{t['name']}\", focus: .{t['focus']},")
        out.append(",\n".join(f"        {k}: Color(hex: 0x{hex6(t[k])})" for k in COLOR_KEYS))
        out.append("    )")
    out.append("    static let themes: [NeonThemeTokens] = [" + ", ".join(camel(t["id"]) for t in TOKENS["themes"]) + "]")
    for group in ["shape", "focus", "motion", "poster"]:
        for k, v in TOKENS[group].items():
            out.append(f"    static let {group}{k[0].upper()}{k[1:]}: CGFloat = {v}")
    for k, v in TOKENS["fonts"].items():
        out.append(f"    static let font{k.title()} = \"{v}\"")
    out.append("}")
    return "\n".join(out) + "\n"


def kotlin():
    out = [f"// {HEADER}", "", "package com.neontokyo.desktop.theme", "", "import androidx.compose.ui.graphics.Color", "",
           "object NeonTokens {"]
    for t in TOKENS["themes"]:
        out.append(f"    val {camel(t['id'])} = NeonThemeTokens(")
        out.append(f"        id = \"{t['id']}\", name = \"{t['name']}\", focus = FocusStyle.{t['focus'].title()},")
        out.append(",\n".join(f"        {k} = Color(0xFF{hex6(t[k])})" for k in COLOR_KEYS))
        out.append("    )")
    out.append("    val themes = listOf(" + ", ".join(camel(t["id"]) for t in TOKENS["themes"]) + ")")
    for group in ["shape", "focus", "motion", "poster"]:
        for k, v in TOKENS[group].items():
            out.append(f"    const val {group}{k[0].upper()}{k[1:]} = {float(v)}f")
    for k, v in TOKENS["fonts"].items():
        out.append(f"    const val font{k.title()} = \"{v}\"")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    check = "--check" in sys.argv
    stale = []
    for path, text in [(SWIFT, swift()), (KOTLIN, kotlin())]:
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print("wrote", path.relative_to(ROOT))
    if stale:
        print("Out of date, run python3 tools/gen_tokens.py:", *stale, sep="\n  ")
        sys.exit(1)


if __name__ == "__main__":
    main()
